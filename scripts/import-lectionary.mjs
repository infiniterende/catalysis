#!/usr/bin/env node
/**
 * Imports the daily Mass reading citations (Lectionary for Mass, United States)
 * from github.com/acupofjose/catholic-readings-api (MIT), pinned to one commit,
 * into packages/lectionary: one JSON file per year, `{ "MM-DD": { first, psalm, second?, gospel } }`.
 *
 *   node scripts/import-lectionary.mjs                 download the pinned commit
 *   node scripts/import-lectionary.mjs --from <dir>    read a local copy of its readings/ folder
 *
 * Only citations are taken, never text: the app shows each reading from its
 * own Bible. Every citation is checked against the app's parser, and the
 * import stops if one cannot be read, except those the Bible cannot hold
 * (Esther's lettered chapters), which are listed.
 */
import { execFileSync } from 'node:child_process';
import { mkdtemp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parsePassage } from '../packages/api/src/readings.ts';

const COMMIT = '504ae811eb7d55ff620a2937abfc43af988e79dd';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'packages/lectionary');
const FIELDS = { firstReading: 'first', psalm: 'psalm', secondReading: 'second', gospel: 'gospel' };
/** Citations naming chapters the Bible does not have; the app links to the USCCB for these. */
const KNOWN_UNREADABLE = /^Esther [A-F]:/;

async function readingsDir() {
  const from = process.argv.indexOf('--from');
  if (from > 0) return { dir: process.argv[from + 1], cleanup: async () => undefined };
  const work = await mkdtemp(join(tmpdir(), 'lectionary-'));
  const archive = join(work, 'source.tar.gz');
  const response = await fetch(`https://codeload.github.com/acupofjose/catholic-readings-api/tar.gz/${COMMIT}`);
  if (!response.ok) throw new Error(`Download failed: ${response.status}`);
  await writeFile(archive, Buffer.from(await response.arrayBuffer()));
  execFileSync('tar', ['xzf', archive, '-C', work]);
  return { dir: join(work, `catholic-readings-api-${COMMIT}`, 'readings'), cleanup: () => rm(work, { recursive: true, force: true }) };
}

const { dir, cleanup } = await readingsDir();
const years = (await readdir(dir)).filter((y) => /^\d{4}$/.test(y)).sort();
const unreadable = [];
const failures = [];
const coverage = {};
for (const year of years) {
  const out = {};
  for (const file of (await readdir(join(dir, year))).filter((f) => f.endsWith('.json')).sort()) {
    const day = JSON.parse(await readFile(join(dir, year, file), 'utf8'));
    const entry = {};
    for (const [field, kind] of Object.entries(FIELDS)) {
      const citation = day.readings?.[field];
      if (typeof citation !== 'string' || !citation.trim()) continue;
      const clean = citation.replace(/\s+/g, ' ').trim();
      if (!parsePassage(clean)) {
        if (!KNOWN_UNREADABLE.test(clean)) failures.push(`${year}-${file.replace('.json', '')} ${kind}: ${clean}`);
        else unreadable.push(`${year}-${file.replace('.json', '')} ${kind}: ${clean}`);
      }
      entry[kind] = clean;
    }
    if (entry.gospel) out[file.replace('.json', '')] = entry;
  }
  await writeFile(join(OUT, `${year}.json`), JSON.stringify(out));
  const days = Object.keys(out);
  coverage[year] = { first: days[0], last: days[days.length - 1], days: days.length };
}
await cleanup();
if (failures.length) {
  console.error(`Citations the parser cannot read (${failures.length}):\n  ${failures.join('\n  ')}`);
  process.exit(1);
}

const first = years.find((y) => coverage[y].days);
const last = [...years].reverse().find((y) => coverage[y].days);
await writeFile(join(OUT, 'index.js'), `// GENERATED by scripts/import-lectionary.mjs — do not edit.
const YEARS = {
${years.map((y) => `  ${y}: () => import('./${y}.json'),`).join('\n')}
};

/** The first and last days with readings. */
export const LECTIONARY_RANGE = { first: '${first}-${coverage[first].first}', last: '${last}-${coverage[last].last}' };

/** The citations for one day (\`YYYY-MM-DD\`), or \`undefined\` if the data has none. */
export async function loadLectionaryDay(date) {
  const load = YEARS[date.slice(0, 4)];
  if (!load) return undefined;
  const module = await load();
  const days = module.default ?? module;
  return days[date.slice(5)];
}
`);
console.log(JSON.stringify(coverage));
console.log(`Unreadable in the app's Bible (shown with a link to the USCCB): ${unreadable.length}`);
for (const line of unreadable) console.log('  ' + line);
